def pendiente(df, var):
    d = df[["Año", var]].dropna()
    if len(d) < 3:
        return np.nan
    return stats.linregress(d["Año"], d[var]).slope


# Cada tendencia usa la serie completa de SU variable (no el panel recortado),
# así funciona aunque el dato de actividad tenga pocos años.
def tendencia_por_depto(df, var):
    return df.groupby("Departamento")[["Año", var]].apply(lambda g: pendiente(g, var))



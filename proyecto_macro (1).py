# Conclusiones del mapa: patrón geográfico norte–sur (latitud del centro de cada departamento).
# Ojo: en el hemisferio sur la latitud es negativa, así que "más al norte" = latitud MAYOR.
def centro_lat(feature):
    coords = np.array([pt for poly in (feature["geometry"]["coordinates"]
                                       if feature["geometry"]["type"] == "MultiPolygon"
                                       else [feature["geometry"]["coordinates"]])
                       for anillo in poly for pt in anillo])
    return coords[:, 1].mean()



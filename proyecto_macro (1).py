# 8. MODELO: ¿qué factores explican el nivel de actividad y en qué medida?
#    log(Actividad) ~ Univ_% + Desempleo_% + Puerto + MVD + Metro + efectos fijos de año
#    - Metro = Canelones y San José (área metropolitana): controla el efecto "ciudad dormitorio".
#    - Efectos fijos de año: compara departamentos dentro del mismo año.
#    - Errores agrupados por departamento: hay 19 departamentos, no 300 obs. independientes.
#    - Pobreza NO entra como predictora: es consecuencia del ingreso/actividad.
#    - Con 19 departamentos, pocas predictoras (acá 5).

SEC = "8. Modelo"
datos = panel.dropna(subset=["log_actividad", "Univ_%", "Desempleo_%", "Puerto"]).copy()
predictoras = ["Univ_%", "Desempleo_%", "Puerto", "MVD", "Metro"]

# Coeficientes estandarizados (cuántos desvíos cambia Y por 1 desvío de X) para comparar factores
datos_z = datos.copy()
for v in ["log_actividad", "Univ_%", "Desempleo_%"]:
    datos_z[v] = (datos[v] - datos[v].mean()) / datos[v].std()

formula = "log_actividad ~ Q('Univ_%') + Q('Desempleo_%') + Puerto + MVD + Metro"
grupos = pd.factorize(datos["Departamento"])[0]
años_distintos = datos["Año"].nunique() > 1
f_full = formula + (" + C(Año)" if años_distintos else "")

modelo = smf.ols(f_full, data=datos).fit(cov_type="cluster", cov_kwds={"groups": grupos})
modelo_z = smf.ols(f_full, data=datos_z).fit(cov_type="cluster", cov_kwds={"groups": grupos})
nombres = {"Q('Univ_%')": "Universidad (%)", "Q('Desempleo_%')": "Desempleo (%)",
           "Puerto": "Puerto", "MVD": "Montevideo", "Metro": "Área metropolitana"}
tabla = pd.DataFrame({
    "coef": modelo.params, "p_valor": modelo.pvalues,
    "efecto_%_en_actividad": (np.exp(modelo.params) - 1) * 100,
    "coef_estandarizado": modelo_z.params,
    "ic95_inf": modelo_z.conf_int()[0], "ic95_sup": modelo_z.conf_int()[1],
}).loc[list(nombres)].rename(index=nombres)
print("\n--- Modelo de actividad ---")
print(tabla.round(3))
print(f"R² = {modelo.rsquared:.2f} | {int(modelo.nobs)} obs | {datos['Departamento'].nunique()} deptos")

# Cuánto explica cada factor solo
r2_solo = {}
for v in predictoras:
    r2_solo[nombres[f"Q('{v}')" if "%" in v else v]] = smf.ols(
        f"log_actividad ~ Q('{v}')", data=datos).fit().rsquared
print("R² de cada factor por separado:", {k: round(v, 2) for k, v in r2_solo.items()})

concluir(SEC, f"El modelo ({'efectos fijos de año' if años_distintos else 'corte transversal'}, "
              f"errores por departamento) explica el {modelo.rsquared:.0%} de la variación del nivel de actividad.")
for nombre_f, fila in tabla.iterrows():
    sig = "significativo" if fila["p_valor"] < 0.05 else "no significativo"
    unidad = ("1 p.p. más" if "%" in nombre_f else
              "ser Montevideo" if nombre_f == "Montevideo" else
              "ser del área metropolitana (Canelones, San José)" if nombre_f == "Área metropolitana"
              else "tener puerto")
    concluir(SEC, f"{nombre_f}: {unidad} se asocia a {fmt(fila['efecto_%_en_actividad'], 1)}% de actividad "
                  f"({sig}, p = {fila['p_valor']:.3f}).")
factor_solo = max(r2_solo, key=r2_solo.get)
concluir(SEC, f"Por sí solo, el factor que más explica es {factor_solo} "
              f"(R² = {r2_solo[factor_solo]:.2f}).")
if tabla.loc["Montevideo", "p_valor"] >= 0.05 and tabla.loc["Universidad (%)", "p_valor"] < 0.05:
    concluir(SEC, "Ser Montevideo deja de importar al controlar por educación: la ventaja de la capital "
                  "se explica en buena parte por su capital humano.")
concluir(SEC, "Son asociaciones, no efectos causales: un factor puede impulsar la actividad, pero también "
              "la actividad puede atraer ese factor (por ejemplo, gente más educada o inversión portuaria).")

if tabla.loc["Área metropolitana", "p_valor"] < 0.05 and tabla.loc["Área metropolitana", "coef"] < 0:
    concluir(SEC, "El área metropolitana (Canelones, San José) tiene menos actividad por residente: "
                  "parte de su población trabaja en Montevideo, donde se registra esa producción.")

# Departamentos por encima/debajo de lo que predice el modelo
datos["residuo"] = modelo.resid
resid_depto = datos.groupby("Departamento")["residuo"].mean().sort_values()
concluir(SEC, f"Más actividad de la que predicen sus factores: {', '.join(resid_depto.index[-3:][::-1])}. "
              f"Menos: {', '.join(resid_depto.index[:3])}. Ahí hay factores que el modelo no captura "
              "(turismo, agro, cercanía a Montevideo, frontera).")


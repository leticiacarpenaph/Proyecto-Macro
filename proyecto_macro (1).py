def parse_numero_uy(valor):
    """'31.701,6' o '10,5' -> float. Punto = miles, coma = decimal."""
    if pd.isna(valor):
        return np.nan
    if isinstance(valor, (int, float)):
        return float(valor)
    s = str(valor).strip()
    if s == "" or s.lower() in ("nan", "..", "-"):
        return np.nan
    s = s.replace(".", "").replace(",", ".")
    try:
        return float(s)
    except ValueError:
        return np.nan


def corregir_miles(v):
    """Ingreso per cápita: algunas celdas perdieron ceros al exportarse
    (ej. Montevideo 2015 = '45.6' en vez de 45.600). Todos los valores reales están
    entre 10.000 y 99.999, así que se multiplica por 10 hasta volver a ese rango."""
    if pd.isna(v):
        return v
    v = float(v)
    while 0 < v < 10_000:
        v *= 10
    return round(v, 1)


def cargar_ancho_a_largo(path, value_name, extra_id_cols=None):
    extra_id_cols = extra_id_cols or []
    if path.suffix.lower() == ".csv":
        df = pd.read_csv(path, sep=";", encoding="utf-8-sig", dtype=str)
    else:
        df = pd.read_excel(path, dtype=str)
    df.columns = [str(c).strip().strip('"') for c in df.columns]
    id_cols = ["Departamento"] + extra_id_cols
    year_cols = [c for c in df.columns if re.fullmatch(r"\d{4}", c)]
    largo = df.melt(id_vars=id_cols, value_vars=year_cols,
                    var_name="Año", value_name=value_name)
    largo["Año"] = largo["Año"].astype(int)
    largo[value_name] = largo[value_name].apply(parse_numero_uy)
    largo["Departamento"] = largo["Departamento"].astype(str).str.strip().str.strip('"')
    largo = largo[largo["Departamento"].str.lower() != "total"]
    return largo.dropna(subset=[value_name])


# Plotly dibuja los polígonos con el borde exterior en sentido HORARIO. geoBoundaries los trae en
# sentido antihorario (estándar GeoJSON), y Plotly los interpreta como "todo el mundo menos el
# departamento": el mapa queda vacío o todo pintado. Acá se da vuelta cada anillo si hace falta.
def _area(anillo):
    return sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(anillo, anillo[1:])) / 2


def _orientar(poligono):
    exterior, *huecos = poligono
    exterior = exterior if _area(exterior) < 0 else exterior[::-1]          # exterior: horario
    huecos = [h if _area(h) > 0 else h[::-1] for h in huecos]               # huecos: antihorario
    return [exterior] + huecos


for f in geo["features"]:
    f["id"] = f["properties"]["shapeName"].strip()
    g = f["geometry"]
    if g["type"] == "Polygon":
        g["coordinates"] = _orientar(g["coordinates"])
    elif g["type"] == "MultiPolygon":
        g["coordinates"] = [_orientar(pol) for pol in g["coordinates"]]

